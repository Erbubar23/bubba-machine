def rows(spec, w):
    out = []
    for r in spec.split('|'):
        assert len(r) == w, (spec, r)
        v = 0
        for i, ch in enumerate(r):
            if ch == '#':
                v |= 1 << (w - 1 - i)
        out.append(v)
    return out


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dst = os.path.join(root, 'core', 'gen', 'bm_font.c')
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    lines = ['/* GENERADO por tools/gen_font.py: no editar a mano. */',
             '#include "../bm_gfx.h"', '',
             '/* 5x7, ASCII 32..127; fila 0 arriba, bit 4 = columna izquierda */',
             'const uint8_t bm_font5x7[96][7] = {']
    for c in range(32, 128):
        ch = chr(c)
        g = F57.get(ch) or F57.get(ch.upper()) or F57[' ']
        lines.append('  {%s}, /* %r */' % (','.join('0x%02X' % v for v in rows(g, 5)), ch))
    lines += ['};', '', '/* 3x5, ASCII 32..127; bit 2 = columna izquierda */',
              'const uint8_t bm_font3x5[96][5] = {']
    for c in range(32, 128):
        ch = chr(c)
        g = F35.get(ch) or F35.get(ch.upper()) or F35[' ']
        lines.append('  {%s}, /* %r */' % (','.join('0x%02X' % v for v in rows(g, 3)), ch))
    lines.append('};')
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('escrito', dst)


if __name__ == '__main__':
    sys.exit(main())
